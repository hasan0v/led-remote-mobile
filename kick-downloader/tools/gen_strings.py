def esc(s):
    s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    s = s.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')
    return s
def write(path, idx):
    with open(path, "w") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<resources>\n')
        for k, v in S.items():
            extra = ' translatable="false"' if v[0] == v[1] and idx == 0 and k in ("app_name","ar_16_9","ar_4_3") else ''
            f.write(f'    <string name="{k}"{extra}>{esc(v[idx])}</string>\n')
        for k, v in PL.items():
            one, other = v[idx]
            f.write(f'    <plurals name="{k}">\n        <item quantity="one">{esc(one)}</item>\n        <item quantity="other">{esc(other)}</item>\n    </plurals>\n')
        f.write('</resources>\n')
